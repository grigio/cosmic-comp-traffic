#!/usr/bin/env bash
# Install the GTK4/libadwaita traffic-light override into the current user's
# config. Re-run this after COSMIC regenerates its GTK CSS on a theme change.
set -euo pipefail

# Resolve symlinks so the script also works when linked into ~/bin or PATH.
script_path="$(readlink -f "${BASH_SOURCE[0]}")"
repo_root="$(cd "$(dirname "$script_path")/.." && pwd)"
src_dir="$repo_root/assets/gtk4/traffic-lights"
config_dir="${XDG_CONFIG_HOME:-$HOME/.config}/gtk-4.0"
gtk3_dir="${XDG_CONFIG_HOME:-$HOME/.config}/gtk-3.0"
cosmic_dir="$config_dir/cosmic"
dest_dir="$cosmic_dir/traffic-lights"
data_dir="${XDG_DATA_HOME:-$HOME/.local/share}"
icons_root="$data_dir/icons/hicolor"
# Do NOT create a hicolor/index.theme here: that would shadow the system
# theme and hide icons such as Brave's launcher icon. GTK finds symbolic icons
# in scalable/actions without an index.theme.
icons_dir="$icons_root/scalable/actions"
# GTK resolves @import relative to ~/.config/gtk-4.0/gtk.css (the path GTK
# opens), not the real path behind COSMIC's gtk.css symlink.
import_line='@import "cosmic/traffic-lights/traffic-lights.css";'

if [[ ! -f "$src_dir/traffic-lights.css" ]]; then
    echo "error: missing $src_dir/traffic-lights.css" >&2
    exit 1
fi

mkdir -p "$dest_dir" "$icons_dir" "$gtk3_dir"
install -m 0644 "$src_dir/traffic-lights.css" "$dest_dir/"

# COSMIC links gtk-3.0/gtk.css at the GTK4 generated file too. GTK3 resolves
# @import relative to gtk-3.0/, so give it a cosmic/ symlink as well; both
# toolkits then read the same override and stay in sync.
if [[ ! -e "$gtk3_dir/cosmic" ]]; then
    ln -s "$cosmic_dir" "$gtk3_dir/cosmic"
fi
install -m 0644 "$src_dir"/*.svg "$icons_dir/"

if command -v gtk4-update-icon-cache >/dev/null 2>&1; then
    # -t ignores the missing theme index; the system hicolor theme owns that.
    gtk4-update-icon-cache -q -f -t "$icons_root" 2>/dev/null || true
fi

# COSMIC's theme writer owns dark.css/light.css. Put the import right after
# the generated-file marker so a running theme still provides the colours.
inserted=0
for css in "$cosmic_dir/dark.css" "$cosmic_dir/light.css"; do
    [[ -f "$css" ]] || continue
    tmp="$(mktemp)"
    # Drop any stale override import first, then put the current one straight
    # after the GENERATED BY COSMIC marker.
    awk -v imp="$import_line" '
        NR == 1 { print; print imp; next }
        /@import/ && /traffic-lights\.css/ { next }
        { print }
    ' "$css" > "$tmp"
    if cmp -s "$css" "$tmp"; then
        rm -f "$tmp"
    else
        mv "$tmp" "$css"
        inserted=1
    fi
done

# gtk.css must resolve to one of those generated files for the import to be
# seen. COSMIC normally creates this symlink itself; don't clobber a custom
# stylesheet, just tell the user what to do about it.
gtk_css="$config_dir/gtk.css"
if [[ -e "$gtk_css" ]]; then
    target="$(readlink -f "$gtk_css" || true)"
    case "$target" in
        "$cosmic_dir"/dark.css|"$cosmic_dir"/light.css) ;;
        *)
            echo "warning: $gtk_css is not linked to COSMIC's dark.css/light.css" >&2
            echo "         add this line to it: $import_line" >&2
            ;;
    esac
fi

if [[ "$inserted" -eq 1 ]]; then
    echo "Installed GTK4 traffic-light override. Restart GTK4/libadwaita apps to see it."
else
    echo "GTK4 traffic-light override is already installed. Restart apps if needed."
fi
